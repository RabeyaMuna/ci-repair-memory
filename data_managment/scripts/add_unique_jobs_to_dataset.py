#!/usr/bin/env python3
"""
Add unique jobs/steps from validation data to the main dataset.

Uses the output from enrich_and_structure_dataset.py to populate the dataset
with UNIQUE jobs and steps (deduped across sha_fail → sha_success trajectory).

NEW COLUMNS (updates existing):
- overall_jobs: List of unique jobs with their steps
- total_jobs: Count of unique jobs
- total_steps: Count of unique steps
- failed_jobs: List of unique failed jobs with their steps
- total_failed_jobs: Count of unique failed jobs
- total_failed_steps: Count of unique failed steps

Input: data_managment/results/filtered_validation/
Output: Updates dataset/lca_dataset.parquet
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Dict, List

import pandas as pd


SCRIPT_DIR = Path(__file__).resolve().parent
DATA_MANAGEMENT_DIR = SCRIPT_DIR.parent
PROJECT_ROOT = DATA_MANAGEMENT_DIR.parent
DATASET_PATH = PROJECT_ROOT / "dataset" / "lca_dataset.parquet"
VALIDATION_DIR = DATA_MANAGEMENT_DIR / "results" / "filtered_validation"

# Input files generated by enrich_and_structure_dataset.py
OVERALL_JOBS_FILE = VALIDATION_DIR / "overall_jobs_by_issue.json"
FAILED_JOBS_FILE = VALIDATION_DIR / "failed_jobs_by_issue.json"


def load_json_file(file_path: Path) -> List[Dict[str, Any]]:
    """Load JSON file."""
    if not file_path.exists():
        raise FileNotFoundError(f"Required file not found: {file_path}\n"
                              f"Run enrich_and_structure_dataset.py first to generate validation data.")

    with open(file_path, 'r') as f:
        data = json.load(f)

    if isinstance(data, dict) and 'instances' in data:
        return data['instances']
    return data


def convert_validation_to_dataset_format(jobs: List[Dict]) -> List[Dict]:
    """
    Convert validation format to dataset format.

    Validation: {'job_name': 'X', 'step_names': [...]}
    Dataset: {'job_name': 'X', 'steps': [...]}
    """
    converted = []
    for job in jobs:
        if not isinstance(job, dict):
            continue

        converted_job = {
            'job_name': job.get('job_name', ''),
            'steps': job.get('step_names', [])
        }
        converted.append(converted_job)

    return converted


def create_unique_jobs_lookup(overall_jobs: List[Dict], failed_jobs: List[Dict]) -> Dict[str, Dict]:
    """Create lookup dictionary by issue ID with unique jobs/steps."""

    lookup = {}

    # Process overall jobs
    for item in overall_jobs:
        issue_id = str(item.get('id', ''))

        jobs = convert_validation_to_dataset_format(item.get('overall_jobs', []))

        lookup[issue_id] = {
            'overall_jobs': jobs,
            'total_jobs': item.get('no_of_jobs', 0),
            'total_steps': item.get('no_of_steps', 0),
        }

    # Process failed jobs
    for item in failed_jobs:
        issue_id = str(item.get('id', ''))

        if issue_id not in lookup:
            lookup[issue_id] = {}

        failed = convert_validation_to_dataset_format(item.get('failed_jobs', []))

        lookup[issue_id].update({
            'failed_jobs': failed,
            'total_failed_jobs': item.get('no_of_failed_jobs', 0),
            'total_failed_steps': item.get('no_of_failed_steps', 0),
        })

    return lookup


def update_dataset_with_unique_jobs(df: pd.DataFrame, unique_jobs_lookup: Dict[str, Dict]) -> pd.DataFrame:
    """Update dataset with unique jobs/steps."""

    print(f"Updating {len(df)} instances with unique jobs/steps...")

    matched = 0
    not_matched = 0

    for idx, row in df.iterrows():
        issue_id = str(row['id'])

        if issue_id in unique_jobs_lookup:
            data = unique_jobs_lookup[issue_id]

            df.at[idx, 'overall_jobs'] = data.get('overall_jobs', [])
            df.at[idx, 'total_jobs'] = data.get('total_jobs', 0)
            df.at[idx, 'total_steps'] = data.get('total_steps', 0)
            df.at[idx, 'failed_jobs'] = data.get('failed_jobs', [])
            df.at[idx, 'total_failed_jobs'] = data.get('total_failed_jobs', 0)
            df.at[idx, 'total_failed_steps'] = data.get('total_failed_steps', 0)

            matched += 1
        else:
            # Set defaults for unmatched
            df.at[idx, 'overall_jobs'] = []
            df.at[idx, 'total_jobs'] = 0
            df.at[idx, 'total_steps'] = 0
            df.at[idx, 'failed_jobs'] = []
            df.at[idx, 'total_failed_jobs'] = 0
            df.at[idx, 'total_failed_steps'] = 0
            not_matched += 1

    print(f"✓ Matched {matched} instances")
    if not_matched > 0:
        print(f"⚠️  {not_matched} instances without validation data (set to empty)")

    return df


def main():
    """Main entry point."""

    print("=" * 70)
    print("ADD UNIQUE JOBS & STEPS TO DATASET")
    print("=" * 70)
    print()
    print("This script uses data generated by:")
    print("  data_managment/scripts/enrich_and_structure_dataset.py")
    print()

    # Load dataset
    print(f"1. Loading dataset from {DATASET_PATH}...")
    if not DATASET_PATH.exists():
        raise FileNotFoundError(f"Dataset not found: {DATASET_PATH}")
    df = pd.read_parquet(DATASET_PATH)
    print(f"   Loaded {len(df)} instances")

    # Load validation data
    print(f"\n2. Loading unique jobs/steps from validation data...")
    overall_jobs = load_json_file(OVERALL_JOBS_FILE)
    print(f"   Overall jobs: {len(overall_jobs)} instances")

    failed_jobs = load_json_file(FAILED_JOBS_FILE)
    print(f"   Failed jobs: {len(failed_jobs)} instances")

    # Create lookup
    print(f"\n3. Creating unique jobs lookup...")
    unique_jobs_lookup = create_unique_jobs_lookup(overall_jobs, failed_jobs)
    print(f"   Lookup created for {len(unique_jobs_lookup)} instances")

    # Update dataset
    print(f"\n4. Updating dataset with unique jobs/steps...")
    df_updated = update_dataset_with_unique_jobs(df, unique_jobs_lookup)

    # Show summary
    print(f"\n5. Summary:")
    total_jobs = df_updated['total_jobs'].sum()
    total_steps = df_updated['total_steps'].sum()
    total_failed_jobs = df_updated['total_failed_jobs'].sum()
    total_failed_steps = df_updated['total_failed_steps'].sum()

    print(f"   Unique jobs: {total_jobs:,}")
    print(f"   Unique steps: {total_steps:,}")
    print(f"   Unique failed jobs: {total_failed_jobs:,}")
    print(f"   Unique failed steps: {total_failed_steps:,}")

    if total_jobs > 0:
        failure_rate = (total_failed_jobs / total_jobs) * 100
        print(f"   Job failure rate: {failure_rate:.2f}%")

    # Save
    print(f"\n6. Saving updated dataset...")
    tmp_path = str(DATASET_PATH) + ".tmp"
    df_updated.to_parquet(tmp_path, index=False)
    os.replace(tmp_path, DATASET_PATH)
    print(f"   ✓ Saved to {DATASET_PATH}")

    # Show sample
    print(f"\n7. Sample instance:")
    sample_df = df_updated[df_updated['total_jobs'] > 0]
    if len(sample_df) > 0:
        sample = sample_df.iloc[0]
        print(f"   ID: {sample['id']}")
        print(f"   Repo: {sample['repo_owner']}/{sample['repo_name']}")
        print(f"   Unique jobs: {sample['total_jobs']}")
        print(f"   Unique steps: {sample['total_steps']}")
        print(f"   Failed jobs: {sample['total_failed_jobs']}")
        print(f"   Failed steps: {sample['total_failed_steps']}")

    print("\n" + "=" * 70)
    print("✅ COMPLETE!")
    print("=" * 70)
    print()
    print("Updated columns (now with UNIQUE counts):")
    print("  • overall_jobs: List of unique jobs with steps")
    print("  • total_jobs: Count of unique jobs")
    print("  • total_steps: Count of unique steps")
    print("  • failed_jobs: List of unique failed jobs")
    print("  • total_failed_jobs: Count of unique failed jobs")
    print("  • total_failed_steps: Count of unique failed steps")
    print()
    print("Note: Counts reflect UNIQUE jobs/steps across sha_fail → sha_success")
    print("      trajectory, not repetitions across commits.")


if __name__ == "__main__":
    main()
